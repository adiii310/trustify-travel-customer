export const starBar = (reviews: Review[]) =>
  [5, 4, 3, 2, 1].map((n) => ({
    stars: n,
    pct: reviews.length
      ? Math.round((100 * reviews.filter((r) => r.rating === n).length) / reviews.length)
      : 0,
  }));

export const averageRating = (reviews: Review[]) =>
  reviews.length
    ? Number((reviews.reduce((t, r) => t + r.rating, 0) / reviews.length).toFixed(1))
    : 0;
